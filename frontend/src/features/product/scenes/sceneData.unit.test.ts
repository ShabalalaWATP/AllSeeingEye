/**
 * The story globe's scene is committed data from a seeded generator. Regenerating it
 * here pins determinism: a changed seed, region, land mask or generator fails until
 * `node scripts/product-scene.js` is re-run and the new file reviewed.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { describe, expect, it } from 'vitest';

import {
  SCENE_SEED,
  buildProductScene,
  readLandMask,
  seededRandom,
  serialiseScene,
} from '../../../../scripts/product-scene.js';
import { LAND_MASK_BASE64 } from './landMask.generated';
import { GENERATED_LAYERS, SCENE_COUNTS, buildScene } from './sceneData';

const COMMITTED = readFileSync(resolve(__dirname, 'sceneData.generated.json'), 'utf8');

describe('illustrative scene', () => {
  it('is regenerated byte for byte from the fixed seed and the packaged land mask', () => {
    expect(SCENE_SEED).toBe(20261007);
    expect(readLandMask(readFileSync(resolve(__dirname, 'landMask.generated.ts'), 'utf8'))).toBe(
      LAND_MASK_BASE64,
    );
    const scene = buildProductScene(LAND_MASK_BASE64);
    expect(serialiseScene(scene)).toBe(COMMITTED);
    expect(scene.layers).toEqual(GENERATED_LAYERS);
    expect(buildProductScene(LAND_MASK_BASE64)).toEqual(scene);
  });

  it('uses a repeatable random sequence', () => {
    const a = seededRandom(7);
    const b = seededRandom(7);
    expect([a(), a(), a()]).toEqual([b(), b(), b()]);
    expect(seededRandom(8)()).not.toBe(seededRandom(7)());
  });

  it('keeps coordinates coarse and bounded, so no point can be a real track', () => {
    for (const layer of GENERATED_LAYERS) {
      const pairs = [...layer.points, ...layer.routes.flat()];
      expect(pairs.length, layer.id).toBeLessThan(200);
      for (const [lat = 0, lon = 0] of pairs) {
        expect(Math.abs(lat)).toBeLessThanOrEqual(90);
        expect(Math.abs(lon)).toBeLessThanOrEqual(180);
        expect(Math.round(lat * 100) / 100).toBe(lat);
        expect(Math.round(lon * 100) / 100).toBe(lon);
      }
    }
  });

  it('draws something for every story layer and counts what it draws', () => {
    for (const layer of buildScene()) {
      const shapes = layer.points.length + layer.routes.length + (layer.kind === 'orbits' ? 1 : 0);
      expect(shapes, layer.id).toBeGreaterThan(0);
      expect(SCENE_COUNTS[layer.id]?.value, layer.id).toBeGreaterThan(0);
    }
    expect(SCENE_COUNTS.space).toEqual({ value: 18, noun: 'satellites' });
    expect(SCENE_COUNTS.aircraft).toEqual({ value: 6, noun: 'routes' });
    expect(SCENE_COUNTS.conflict?.noun).toBe('points');
    // Routes are interpolated along great circles from their stored waypoints.
    const aircraft = buildScene().find((layer) => layer.id === 'aircraft');
    expect(aircraft?.routes[0]).toHaveLength(49);
  });
});
