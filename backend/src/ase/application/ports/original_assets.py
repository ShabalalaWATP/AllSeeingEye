"""Transactional original-byte storage. Caller holds the shared administration guard."""

from datetime import datetime
from typing import Protocol
from uuid import UUID

from ase.domain.original_assets import OriginalAsset, OriginalAssetContent


class OriginalAssetRepository(Protocol):
    async def expire(self, now: datetime) -> None: ...
    async def usage(
        self, owner_id: UUID | None = None, team_id: UUID | None = None, *, live_only: bool = False
    ) -> tuple[int, int]:
        """Count records and declared bytes; live_only excludes scrubbed lifecycle rows."""
        ...

    async def retired_count(self, uploader_id: UUID) -> int:
        """Count deleted/expired rows for the uploader across every scope and session."""
        ...

    async def pending_count(self, uploader_id: UUID | None = None) -> int: ...
    async def create(self, asset: OriginalAsset) -> None: ...
    async def get(self, asset_id: UUID) -> OriginalAsset | None: ...
    async def list(self, report_id: UUID, version_number: int) -> tuple[OriginalAsset, ...]: ...
    async def begin_upload(self, asset_id: UUID, now: datetime) -> bool: ...
    async def activate(self, asset_id: UUID, content: bytes, now: datetime) -> bool: ...
    async def content(self, asset_id: UUID) -> OriginalAssetContent | None: ...
    async def delete(self, asset_id: UUID, now: datetime) -> None: ...
